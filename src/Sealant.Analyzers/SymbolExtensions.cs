using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Sealant.Analyzers;

internal static class SymbolExtensions
{
    private const string TemporaryGeneratedFilePrefix = "TemporaryGeneratedFile_";
    private const string UnsealedCommentText = "unsealed";

    private static readonly string[] GeneratedFileStems = [".g", ".g.i", ".generated", ".designer"];

    public static bool HasSourceDeclaration(this ISymbol symbol)
    {
        foreach (var reference in symbol.DeclaringSyntaxReferences)
        {
            if (reference.GetSyntax() is TypeDeclarationSyntax)
            {
                return true;
            }
        }

        return false;
    }

    public static bool HasUnsealedComment(this ISymbol symbol, Ct ct)
    {
        foreach (var reference in symbol.DeclaringSyntaxReferences)
        {
            if (reference.GetSyntax(ct) is TypeDeclarationSyntax declaration && declaration.HasUnsealedComment())
            {
                return true;
            }
        }

        return false;
    }

    public static Location GetFirstNonGeneratedLocation(this ISymbol symbol)
    {
        foreach (var location in symbol.Locations)
        {
            if (location.SourceTree is { } tree && !tree.IsGenerated() && !location.IsInGeneratedDeclaration(symbol))
            {
                return location;
            }
        }

        return symbol.Locations[0];
    }

    private static bool HasUnsealedComment(this TypeDeclarationSyntax declaration)
    {
        if (declaration.AttributeLists.Count > 0)
        {
            var lastAttributeList = declaration.AttributeLists[declaration.AttributeLists.Count - 1];

            if (HasUnsealedComment(lastAttributeList.CloseBracketToken.TrailingTrivia))
            {
                return true;
            }
        }

        foreach (var modifier in declaration.Modifiers)
        {
            if (HasUnsealedComment(modifier.LeadingTrivia))
            {
                return true;
            }

            if (!modifier.IsKind(SyntaxKind.PartialKeyword) && HasUnsealedComment(modifier.TrailingTrivia))
            {
                return true;
            }
        }

        return !declaration.Keyword.GetPreviousToken().IsKind(SyntaxKind.PartialKeyword) &&
            HasUnsealedComment(declaration.Keyword.LeadingTrivia);
    }

    private static bool HasUnsealedComment(SyntaxTriviaList trivia)
    {
        foreach (var item in trivia)
        {
            if (item.IsKind(SyntaxKind.SingleLineCommentTrivia) &&
                item.ToString().TrimStart('/').Trim().Equals(UnsealedCommentText, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private static bool IsInGeneratedDeclaration(this Location location, ISymbol symbol)
    {
        foreach (var reference in symbol.DeclaringSyntaxReferences)
        {
            if (reference.SyntaxTree == location.SourceTree &&
                reference.Span.Contains(location.SourceSpan) &&
                reference.GetSyntax() is TypeDeclarationSyntax declaration)
            {
                return declaration.HasGeneratedCodeAttribute();
            }
        }

        return false;
    }

    private static bool HasGeneratedCodeAttribute(this TypeDeclarationSyntax declaration)
    {
        foreach (var attributeList in declaration.AttributeLists)
        {
            foreach (var attribute in attributeList.Attributes)
            {
                var name = attribute.Name.ToString();

                if (name.EndsWith("GeneratedCode", StringComparison.Ordinal) ||
                    name.EndsWith("GeneratedCodeAttribute", StringComparison.Ordinal) ||
                    name.EndsWith("CompilerGenerated", StringComparison.Ordinal) ||
                    name.EndsWith("CompilerGeneratedAttribute", StringComparison.Ordinal))
                {
                    return true;
                }
            }
        }

        return false;
    }

    private static bool IsGenerated(this SyntaxTree tree) =>
        IsGeneratedFile(tree.FilePath) || tree.HasAutoGeneratedComment();

    private static bool IsGeneratedFile(string path)
    {
        var fileName = GetFileName(path);

        if (fileName.StartsWith(TemporaryGeneratedFilePrefix, StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        var stem = fileName.Substring(0, fileName.Length - Path.GetExtension(fileName).Length);

        foreach (var generatedStem in GeneratedFileStems)
        {
            if (stem.EndsWith(generatedStem, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasAutoGeneratedComment(this SyntaxTree tree)
    {
        foreach (var trivia in tree.GetRoot().GetLeadingTrivia())
        {
            if (!trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) &&
                !trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
            {
                continue;
            }

            var text = trivia.ToString();

            if (text.IndexOf("<autogenerated", StringComparison.Ordinal) >= 0 ||
                text.IndexOf("<auto-generated", StringComparison.Ordinal) >= 0)
            {
                return true;
            }
        }

        return false;
    }

    // Path.GetFileName is host-dependent but the driver treats slash, backslash, and colon as separators on every host
    private static string GetFileName(string path)
    {
        var lastSeparator = path.LastIndexOfAny(['/', '\\', ':']);
        return lastSeparator < 0 ? path : path.Substring(lastSeparator + 1);
    }
}
