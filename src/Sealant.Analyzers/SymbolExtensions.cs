using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Sealant.Analyzers;

internal static class SymbolExtensions
{
    public static bool HasTypeDeclaration(this ITypeSymbol symbol, Ct ct)
    {
        foreach (var reference in symbol.DeclaringSyntaxReferences)
        {
            if (reference.GetSyntax(ct) is TypeDeclarationSyntax)
            {
                return true;
            }
        }

        return false;
    }

    public static Location GetFirstNonGeneratedLocation(this ISymbol symbol, Ct ct)
    {
        foreach (var location in symbol.Locations)
        {
            if (location.SourceTree is not { } tree ||
                tree.HasGeneratedFilePath() ||
                tree.HasAutoGeneratedComment(ct) ||
                symbol.HasGeneratedAttributeAt(location, ct))
            {
                continue;
            }

            return location;
        }

        return symbol.Locations[0];
    }

    private static bool HasGeneratedFilePath(this SyntaxTree tree)
    {
        // Path.GetFileName is host-dependent
        // but the driver treats slash, backslash, and colon as separators on every host
        var lastSeparator = tree.FilePath.LastIndexOfAny(['/', '\\', ':']);
        var filePath = lastSeparator < 0 ? tree.FilePath : tree.FilePath.Substring(lastSeparator + 1);

        if (filePath.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        var stem = filePath.Substring(0, filePath.Length - Path.GetExtension(filePath).Length);

        return
            stem.EndsWith(".g", StringComparison.OrdinalIgnoreCase) ||
            stem.EndsWith(".g.i", StringComparison.OrdinalIgnoreCase) ||
            stem.EndsWith(".generated", StringComparison.OrdinalIgnoreCase) ||
            stem.EndsWith(".designer", StringComparison.OrdinalIgnoreCase);
    }

    private static bool HasAutoGeneratedComment(this SyntaxTree tree, Ct ct)
    {
        foreach (var trivia in tree.GetRoot(ct).GetLeadingTrivia())
        {
            if (!trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) &&
                !trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
            {
                continue;
            }

            var text = trivia.ToString();

            if (text.IndexOf("<autogenerated", StringComparison.Ordinal) >= 0 ||
                text.IndexOf("<auto-generated", StringComparison.Ordinal) >= 0)
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasGeneratedAttributeAt(this ISymbol symbol, Location location, Ct ct)
    {
        foreach (var reference in symbol.DeclaringSyntaxReferences)
        {
            if (reference.SyntaxTree != location.SourceTree ||
                !reference.Span.Contains(location.SourceSpan) ||
                reference.GetSyntax(ct) is not TypeDeclarationSyntax declaration)
            {
                continue;
            }

            foreach (var attributeList in declaration.AttributeLists)
            {
                foreach (var attribute in attributeList.Attributes)
                {
                    var name = attribute.Name.ToString();

                    if (name.EndsWith("GeneratedCode", StringComparison.Ordinal) ||
                        name.EndsWith("GeneratedCodeAttribute", StringComparison.Ordinal) ||
                        name.EndsWith("CompilerGenerated", StringComparison.Ordinal) ||
                        name.EndsWith("CompilerGeneratedAttribute", StringComparison.Ordinal))
                    {
                        return true;
                    }
                }
            }
        }

        return false;
    }

    public static Visibilities ToVisibilities(this INamedTypeSymbol type) =>
        type.IsFileLocal
            ? Visibilities.File
            : type.DeclaredAccessibility switch
            {
                Accessibility.Public => Visibilities.Public,
                Accessibility.Protected => Visibilities.Protected,
                Accessibility.Internal => Visibilities.Internal,
                Accessibility.Private => Visibilities.Private,
                Accessibility.ProtectedOrInternal => Visibilities.ProtectedOrInternal,
                Accessibility.ProtectedAndInternal => Visibilities.ProtectedAndInternal,
                Accessibility.NotApplicable => Visibilities.Private, // no declared accessibility
                _ => Visibilities.Private,
            };

    public static bool HasUnsealedComment(this ISymbol symbol, Ct ct)
    {
        foreach (var reference in symbol.DeclaringSyntaxReferences)
        {
            if (reference.GetSyntax(ct) is TypeDeclarationSyntax declaration && declaration.HasUnsealedComment())
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasUnsealedComment(this TypeDeclarationSyntax declaration)
    {
        if (declaration.AttributeLists.Count > 0)
        {
            var lastAttributeList = declaration.AttributeLists[declaration.AttributeLists.Count - 1];

            if (lastAttributeList.CloseBracketToken.TrailingTrivia.HasUnsealedComment())
            {
                return true;
            }
        }

        foreach (var modifier in declaration.Modifiers)
        {
            if (modifier.LeadingTrivia.HasUnsealedComment())
            {
                return true;
            }

            if (!modifier.IsKind(SyntaxKind.PartialKeyword) && modifier.TrailingTrivia.HasUnsealedComment())
            {
                return true;
            }
        }

        return !declaration.Keyword.GetPreviousToken().IsKind(SyntaxKind.PartialKeyword) &&
            declaration.Keyword.LeadingTrivia.HasUnsealedComment();
    }

    private static bool HasUnsealedComment(this SyntaxTriviaList trivia)
    {
        foreach (var item in trivia)
        {
            if (item.IsKind(SyntaxKind.SingleLineCommentTrivia) &&
                item.ToString().TrimStart('/').Trim().Equals("unsealed", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }
}
